<?php
declare(strict_types=1);

/*
Solution Title: Kaggle Dataset Summary
Solution Summary: Lightweight PHP view over a curated Kaggle summary artifact generated by the Kaggle ingestion overlay.
Solution Tag: kaggle
*/

$defaultSummary = dirname(__DIR__) . '/data/curated/kaggle/stroke_prediction/stroke_prediction_summary.json';
$summaryPath = getenv('KAGGLE_CURATED_SUMMARY_PATH') ?: $defaultSummary;

if (isset($_GET['summary']) && is_string($_GET['summary']) && $_GET['summary'] !== '') {
  $candidate = $_GET['summary'];
  if ($candidate[0] === DIRECTORY_SEPARATOR) {
    $summaryPath = $candidate;
  } else {
    $summaryPath = dirname(__DIR__) . '/' . ltrim($candidate, '/');
  }
}

$page_title = 'Kaggle Dataset Summary';
$page_description = 'Lightweight PHP view over a curated Kaggle summary artifact.';

$summary = null;
$error = null;

if (is_file($summaryPath)) {
  $rawJson = file_get_contents($summaryPath);
  if ($rawJson === false) {
    $error = 'Unable to read curated summary JSON.';
  } else {
    $summary = json_decode($rawJson, true);
    if (!is_array($summary)) {
      $error = 'Curated summary JSON is not valid.';
      $summary = null;
    }
  }
} else {
  $error = 'Curated summary JSON not found.';
}

ob_start();
?>
<h1>Kaggle Dataset Summary</h1>
<h3><a href="/index.php">Services</a> &nbsp; <a href="/health.php">Health</a> &nbsp; <a href="/solutions.php">Solutions</a></h3>
<p><strong>Summary path:</strong> <code><?= htmlspecialchars($summaryPath) ?></code></p>

<?php if ($error !== null): ?>
  <div class="card">
    <h2>Status</h2>
    <p><?= htmlspecialchars($error) ?></p>
    <p>Run the overlay scripts first, or provide a different file with <code>?summary=relative/path/to/summary.json</code>.</p>
  </div>
<?php else: ?>
  <div class="card">
    <h2>Overview</h2>
    <table class="tiers-compare">
      <tbody>
        <tr><th style="width: 220px;">Dataset</th><td><?= htmlspecialchars((string) ($summary['dataset'] ?? '')) ?></td></tr>
        <tr><th>Job name</th><td><?= htmlspecialchars((string) ($summary['job_name'] ?? '')) ?></td></tr>
        <tr><th>Row count</th><td><?= htmlspecialchars((string) ($summary['row_count'] ?? '')) ?></td></tr>
        <tr><th>Column count</th><td><?= htmlspecialchars((string) ($summary['column_count'] ?? '')) ?></td></tr>
        <tr><th>Raw bucket</th><td><code><?= htmlspecialchars((string) ($summary['raw_bucket'] ?? '')) ?></code></td></tr>
        <tr><th>Raw prefix</th><td><code><?= htmlspecialchars((string) ($summary['raw_prefix'] ?? '')) ?></code></td></tr>
        <tr><th>Conformed bucket</th><td><code><?= htmlspecialchars((string) ($summary['conformed_bucket'] ?? '')) ?></code></td></tr>
        <tr><th>Conformed target</th><td><code><?= htmlspecialchars((string) ($summary['conformed_target'] ?? '')) ?></code></td></tr>
        <tr><th>Curated bucket</th><td><code><?= htmlspecialchars((string) ($summary['curated_bucket'] ?? '')) ?></code></td></tr>
        <tr><th>Curated target</th><td><code><?= htmlspecialchars((string) ($summary['curated_target'] ?? '')) ?></code></td></tr>
      </tbody>
    </table>
  </div>

  <div class="card">
    <h2>Columns</h2>
    <?php if (!empty($summary['columns']) && is_array($summary['columns'])): ?>
      <ul>
        <?php foreach ($summary['columns'] as $column): ?>
          <li><code><?= htmlspecialchars((string) $column) ?></code></li>
        <?php endforeach; ?>
      </ul>
    <?php else: ?>
      <p>No columns recorded.</p>
    <?php endif; ?>
  </div>

  <div class="card">
    <h2>Numeric Metrics</h2>
    <?php if (!empty($summary['numeric_stats']) && is_array($summary['numeric_stats'])): ?>
      <table class="tiers-compare">
        <thead>
          <tr>
            <th>Column</th>
            <th>Count</th>
            <th>Mean</th>
            <th>Min</th>
            <th>Max</th>
            <th>Sum</th>
          </tr>
        </thead>
        <tbody>
          <?php foreach ($summary['numeric_stats'] as $column => $stats): ?>
            <tr>
              <td><code><?= htmlspecialchars((string) $column) ?></code></td>
              <td><?= htmlspecialchars((string) ($stats['count'] ?? '')) ?></td>
              <td><?= htmlspecialchars((string) ($stats['mean'] ?? '')) ?></td>
              <td><?= htmlspecialchars((string) ($stats['min'] ?? '')) ?></td>
              <td><?= htmlspecialchars((string) ($stats['max'] ?? '')) ?></td>
              <td><?= htmlspecialchars((string) ($stats['sum'] ?? '')) ?></td>
            </tr>
          <?php endforeach; ?>
        </tbody>
      </table>
    <?php else: ?>
      <p>No numeric metrics recorded.</p>
    <?php endif; ?>
  </div>

  <div class="card">
    <h2>Null Counts</h2>
    <?php if (!empty($summary['null_counts']) && is_array($summary['null_counts'])): ?>
      <table class="tiers-compare">
        <thead>
          <tr><th>Column</th><th>Null count</th></tr>
        </thead>
        <tbody>
          <?php foreach ($summary['null_counts'] as $column => $nullCount): ?>
            <tr>
              <td><code><?= htmlspecialchars((string) $column) ?></code></td>
              <td><?= htmlspecialchars((string) $nullCount) ?></td>
            </tr>
          <?php endforeach; ?>
        </tbody>
      </table>
    <?php else: ?>
      <p>No null count metrics recorded.</p>
    <?php endif; ?>
  </div>
<?php endif; ?>
<?php
$content = ob_get_clean();
$layoutPath = dirname(__DIR__) . '/inc/layout.php';

if (is_file($layoutPath)) {
  require $layoutPath;
  return;
}
?>
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title><?= htmlspecialchars($page_title) ?></title>
  <style>
    body { font-family: sans-serif; margin: 2rem; }
    code { background: #f3f4f6; padding: 0.1rem 0.3rem; }
    .card { margin-bottom: 1.5rem; padding: 1rem; border: 1px solid #d1d5db; border-radius: 8px; }
    table { width: 100%; border-collapse: collapse; }
    th, td { border: 1px solid #d1d5db; padding: 0.5rem; text-align: left; vertical-align: top; }
  </style>
</head>
<body>
  <?= $content ?>
</body>
</html>
